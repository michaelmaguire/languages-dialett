def apply_overrides(pairs):
    """etc/pair_corrections.csv columns: source,line,action,italian,dialect,english,note,kind
    action = delete | replace (blank fields are left as they are) | add. kind (word | expression) is
    optional; an added pair takes the variety of the pair at the same source and line, if there is one."""
    by = {(p["source"], p["line"]): p for p in pairs}
    for o in read(ETC / "pair_corrections.csv"):
        act = o.get("action", "").strip().lower()
        p = by.get((o["source"], o["line"]))
        if act == "delete" and p:
            p["_drop"] = True
        elif act == "replace" and p:
            for f in ("italian", "dialect", "english", "note", "kind"):
                if o.get(f):
                    p[f] = o[f]
            p["check"] = ""
        elif act == "add":
            pairs.append({"italian": o["italian"], "dialect": o["dialect"], "english": o.get("english", ""),
                          "kind": o.get("kind") or ("word" if len(o["italian"].split()) <= 3 else "expression"),
                          "variety": p["variety"] if p else "Rögn (Arogno)",
                          "canonical": p["canonical"] if p else "yes", "source": o["source"] or "my notes",
                          "line": o["line"], "check": "", "note": o.get("note", "")})
    return [p for p in pairs if not p.get("_drop")]


CLASSES = {
    "1": "1st conjugation: infinitive in -à (Italian -are)",
    "2": "2nd conjugation: infinitive in -é (Italian -ere, stressed ending)",
    "3": "3rd conjugation: infinitive with no ending (Italian -ere, unstressed ending)",
    "4": "4th conjugation: infinitive in -ì (Italian -ire)",
    "irr": "irregular",
}
IRREGULAR = {"essere", "avere", "andare", "fare", "dare", "stare", "dire"}
BASE_OF = {"na": "andare", "nà": "andare", "fa": "fare", "fà": "fare"}      # na föra, fa sù ...


def verb_class(name, e, manual):
    """Conjugation class, using the four-class scheme of Western Lombard grammars. Worked out
    from the dialect infinitive unless etc/verb_details.csv says otherwise."""
    given = manual.get(key(name), {}).get("class")
    if given:
        return CLASSES[given]
    if name in IRREGULAR:
        return CLASSES["irr"]
    if not e["dialect"]:
        return ""
    first = re.split(r"\s+o\s+|\s*/\s*|-", e["dialect"][0])[0].split()
    if len(first) > 1 and first[0] in BASE_OF:
        return f"irregular (compound of {first[0]}, {BASE_OF[first[0]]})"
    w = first[0]
    num = "1" if w[-1] in "aà" else "2" if w[-1] in "éè" else "4" if w[-1] in "ìí" else "3"
    return CLASSES[num]


def reassign_verb_forms(verbs):
    """etc/verb_forms_reassigned.csv (source,line,from_italian,to_italian,reason): forms that the parser filed
    under the wrong verb because two dialect verbs share an Italian infinitive (ciapà and töö both translate
    'prendere'). Each row moves the forms of one document line to another Italian verb name."""
    moves = {(r["source"], r["line"], key(r["from_italian"])): r["to_italian"] for r in read(ETC / "verb_forms_reassigned.csv")}
    used = set()
    for v in verbs:
        k = (v["source"], str(v["line"]), key(v["verb_italian"]))
        if k in moves:
            v["verb_italian"] = moves[k]
            used.add(k)
    for k in moves.keys() - used:
        print(f"  WARNING: verb form reassignment matched nothing: {k}")
    return verbs


def drop_particle(form, particles):
    """etc/verb_details.csv `drop_particle`: a particle that is not part of the verb (the gh’ of 'gh’avria',
    like French y), taken out, with the clitic before a vowel then elided: 'ta gh’avressat' -> 't’avressat',
    'al gh’avria/al gh’avressa / la gh’avria/la gh’avressa vüü' -> 'l’avria/l’avressa vüü'."""
    for p in particles:
        pat = re.sub(r"['’]", "['’]", re.escape(p.strip()))
        form = re.sub(rf"(?<![\w’']){pat}\s*", "", form)
    form = re.sub(r"\b(?:la/al|al/la)\s+(?=[aeiouàèéìòóùöü])", "l’", form)
    form = re.sub(r"(?<![\w’])(?:al|la)\s+(?=[aeiouàèéìòóùöü])", "l’", form)
    form = re.sub(r"(?<![\w’])ta\s+(?=[aeiouàèéìòóùöü])", "t’", form)
    m = re.match(r"^(.+) / \1(\s.*)?$", form)            # both clitics written out, now the same
    return (m.group(1) + (m.group(2) or "")) if m else form


def shown_form(name, tense, form, manual):
    """A verb form as the pages show it, so that the lexicon cites its source under the same spelling."""
    form = clitic_order(form)
    if tense == "condizionale presente":
        form = join_endings(form).lower()
    m = manual.get(key(name), {})
    if m.get("drop_particle") and tense in (m.get("drop_particle_tenses") or "").split(";"):
        form = drop_particle(form, m["drop_particle"].split(";"))
    return form


