T_DROP = re.compile(r"^((?:ti\s+)?ta\s+(?:(?:sa|ga|ma|la|ia|na|ta)\s+)*(?:gh[’'])?)(?!(?:sa|ga|ma|la|ia|na|ta)\s)([^\s/()]*[aeiouàáèéìíòóùúü])(?=\s|$)", re.I)


def optional_t(text):
    """The 2nd person singular ends in -t, which the teacher drops when it sounds better (owner, 2026-10-26):
    a ti form written without it shows the t in brackets, 'ta se' -> 'ta se(t)', 'ta naré giò' ->
    'ta naré(t) giò'; 'ta set / ta se' becomes 'ta se(t)'. Forms ending in -t are unchanged."""
    if not text or text == "–":
        return text
    out = {}
    alts = re.split(r"\s+/\s+", text)
    for i, alt in enumerate(alts):
        if i and not re.match(r"(ti\s+)?ta\s", alt, re.I) and re.match(r"(ti\s+)?ta\s", alts[0], re.I):
            alt = "ta " + alt                                   # 'ta gavaré / gavré': the clitic is shared
            shown = T_DROP.sub(lambda m: m.group(1) + m.group(2) + "(t)", alt, count=1)[3:]
            k = key("ta " + shown.replace("(t)", "t"))
        else:
            shown = T_DROP.sub(lambda m: m.group(1) + m.group(2) + "(t)", alt, count=1)
            k = key(shown.replace("(t)", "t"))
        if k not in out or "(t)" in shown:
            out[k] = shown
    return " / ".join(out.values())


def to_verb(en):
    """English of a verb with its "to": 'eat' -> 'to eat'; one written with it already ('to lose') is kept."""
    return "" if not en else en if en.startswith("to ") else f"to {en}"


def dialect_shown(p):
    """The dialect form as printed: an adjective with its feminine (bagnaa/bagnada), † after a form that is
    predicted rather than found in a document (bass/bassa †; sec †/seca when the source has only seca)."""
    if p.get("pos") == "adjective" and p.get("feminine"):
        masc = p["dialect"] + (INFERRED if p.get("masculine_inferred") else "")
        return feminine.with_feminine(masc, p["feminine"] + (INFERRED if p.get("feminine_inferred") else ""))
    return p["dialect"]


def word_label(p, lang="en"):
    """'n. m., pl. purcei' for a noun, 'adj.' for an adjective (its feminine is shown with the headword, dialect_shown), 'adv.' …; in Italian with
    lang='it' ('s. m., pl. purcei', 'agg.'). '' for an entry with no part of speech."""
    pos = p.get("pos") or ""
    abbr = POS_ABBR.get(pos, ("", ""))[lang == "it"]
    extra = ""
    if pos == "noun" and p.get("gender"):
        extra = f"{p['gender']}., pl. {p['plural']}" if p.get("plural") else f"{p['gender']}."
        if p.get("partner"):                                     # n. m., pl. nonu; f. nona
            extra += "; " + p["partner"]
    if pos == "verb" and p.get("principal"):
        return f"{abbr} ({p['principal']})"                     # v. (trövi, truaa): 1st singular, participle
    if pos == "noun":
        return " ".join(x for x in (abbr, extra) if x)            # n. m., pl. purcei
    return ", ".join(x for x in (abbr, extra) if x)


SPELLINGS = re.compile(r"\s*/\s*|\s+o\s+")


def same_letters(form):
    """'pée' -> 'pe', 'giô' -> 'gio': the letters without accents or doubling, to compare spellings."""
    return re.sub(r"(.)\1+", r"\1", plain(form))


def cross_references(words):
    """For the Dialett look-up: one extra row per alternate spelling, in its own alphabetical place, with the
    main spelling in brackets and the same Italian and English ('cumün (= comün) · comune · municipality',
    'scultà (= scoltà)'), so a word can be found, and understood, however it is written (owner, 2026-10-28)."""
    out, seen = [], set()
    for p in words:
        # a leading article pair is definite/indefinite, not two spellings: 'ul/un purcel' has no
        # alternate 'un purcel', so the article is set aside before looking for alternatives
        # likewise a bracketed aside ('furmagela (grasa/magra)') is not split into spellings
        bare_head = re.sub(r"\([^)]*\)", " ", DI_ARTICLE.sub("", p["dialect"]))
        forms = [f.strip() for f in SPELLINGS.split(bare_head) if f.strip()]
        for f in forms[1:]:
            # a spelling that differs only in accents or a doubled letter (pé, pée, pee for pè) sorts next to
            # the entry anyway: a pointer there would only look like a duplicate
            if same_letters(f) == same_letters(forms[0]):
                continue
            label = f"{f} (= {forms[0]})"
            if (key(label), key(p["italian"])) not in seen:      # every sense, each once (trüsà, trüsà o rügà)
                seen.add((key(label), key(p["italian"])))
                out.append(dict(p, dialect=label, note="", check="",
                                gender="", plural="", pos="", feminine="", feminine_inferred="", masculine_inferred="", partner="",
                                principal="", entry_note="", entry_note_en=""))
    return out


def dictionary_table(part, entries):
    """One Markdown table of a look-up: a row per headword, each sense on its own line inside the cells."""
    names = {"dialect": "Dialett", "italian": "Italiano", "english": "English", "region": "Region",
             "note": "Note", "source": "Source"}
    cols = [c for c in ("dialect", "italian", "english") if c != part["head"]] + ["region", "note", "source"]
    show = {"dialect": lambda s: s["dialect"] + (f" *{s['label']}*" if s["label"] else "") + (FLAG if s["check"] else ""),
            "italian": lambda s: s["italian"], "english": lambda s: s["english"], "region": lambda s: s["region"],
            "source": lambda s: src_link(s["source"], text="↗")}

    def head_cell(e):
        if part["head"] != "dialect":
            return e["head"]
        return " · ".join(e["words"]) + (FLAG if e["flag"] else "")

    body = [[head_cell(e)] + ["<br>".join(e["notes"]) if c == "note" else "<br>".join(show[c](s) for s in e["senses"])
                              for c in cols] for e in entries]
    return table([names[part["head"]]] + [names[c] for c in cols], body)


def dictionary_page(part):
    """A look-up page: the letters, then a table per letter (English: one table, no letters)."""
    if part["head"] == "english":
        return "\n".join([f"# {part['title']}\n", f"The {part['blank']} entries that have no English yet are at the end.\n",
                          dictionary_table(part, [e for s in part["sections"] for e in s["entries"]])])
    out = [f"# {part['title']}\n", " · ".join(f"[{s['name']}](#{s['name'].lower()})" for s in part["sections"]
                                              if len(s["name"]) == 1) + "\n"]
    for s in part["sections"]:
        out += [f"## {s['name']}\n", dictionary_table(part, s["entries"])]
    return "\n".join(out)


def join_endings(form):
    """The conditional sheets write 'ciapa-ria/ress' to show stem and endings. Write the
    words out instead: 'ciaparia/ciaparess'."""
    def whole(m):
        stem, first, second = m.group(1), m.group(2), m.group(3)
        if not second:
            return stem + first
        if second[0] == stem[-1] and second[0] not in "aeiou":      # gh'av-rian/vressan
            second = second[1:]
        return f"{stem}{first}/{stem}{second}"
    return re.sub(r"([^\s/]+?)\s*[-.]\s*([^\W\d_]+)(?:/([^\W\d_]+))?", whole, form)


