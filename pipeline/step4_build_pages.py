def verb_tables(verbs):
    """Group conjugated forms by verb. etc/verb_details.csv supplies what the documents do not state
    outright: which entries are the same verb, and the dialect infinitive where it had to be
    found elsewhere in the texts or worked out from the verb's other forms."""
    manual = {key(r["italian"]): r for r in read(ETC / "verb_details.csv")}
    out = OrderedDict()
    for v in verbs:
        name = v["verb_italian"]
        target = manual.get(key(name), {}).get("merge_into")
        alias = ""
        if target:
            if name.startswith(("aver ", "essere ")):      # "aver mangiato" headed a compound-tense table
                v = dict(v, verb_dialect="")
            elif " " not in name:
                alias = name                               # a second Italian verb, same dialect verb
            name = target
        if v["canonical"] != "yes" or not name or len(name.split()) > 3 or name.startswith("col"):
            continue
        e = out.setdefault(name, {"dialect": [], "forms": defaultdict(lambda: defaultdict(list)),
                                  "italian": defaultdict(dict), "sources": [], "aliases": []})
        if alias and alias not in e["aliases"]:
            e["aliases"].append(alias)
        if v["verb_dialect"] and v["verb_dialect"] not in e["dialect"]:
            e["dialect"].append(v["verb_dialect"])
        v = dict(v, form=shown_form(name, v["tense"], v["form"], manual))
        if key(v["form"]) in ("ma", "ta", "sa", "i", "la/al", "al/la", "a"):      # a stray clitic, not a form
            continue
        slot = e["forms"][v["tense"]][v["person"]]
        bare_form = key(conjugate.strip_clitics(v["form"]))
        same = [i for i, x in enumerate(slot) if key(conjugate.strip_clitics(x)) == bare_form]
        if not same:
            slot.append(v["form"])
        elif len(v["form"]) > len(slot[same[0]]):       # same form, this one written with its clitic
            slot[same[0]] = v["form"]
        if v["italian_form"]:
            e["italian"][v["tense"]][v["person"]] = v["italian_form"]
        if v["source"] not in e["sources"]:
            e["sources"].append(v["source"])
    # a verb the lessons never conjugate in a table (töö, duprà) gets a page from etc/verb_details.csv when
    # etc/verb_forms_from_texts.csv has forms of it found in a document
    # (or, like trà, has only its infinitive in a document: verb_details basis attested, every form supplied)
    found = defaultdict(list)
    for r in read(ETC / "verb_forms_from_texts.csv"):
        m = manual.get(key(r["italian"]), {})
        if r.get("source") and (r["basis"] == "attested" or m.get("basis") == "attested"):
            found[key(r["italian"])].append(r["source"])
    for k, m in manual.items():
        # an inferred verb asked for by the owner (guardas, the reflexive of guardà) gets a page with no form
        # found at all: every form is then predicted (†)
        if m.get("dialect") and not m.get("merge_into") and (k in found or m.get("basis") == "inferred") \
                and m["italian"] not in out:
            out[m["italian"]] = {"dialect": [], "forms": defaultdict(lambda: defaultdict(list)),
                                 "italian": defaultdict(dict), "sources": list(dict.fromkeys(found[k])), "aliases": []}
    for name, e in out.items():
        m = manual.get(key(name))
        e["basis"], e["evidence"] = "", ""
        if m and m["dialect"]:
            e["dialect"] = [d.strip() for d in m["dialect"].split(" / ")]
            e["basis"], e["evidence"] = m["basis"], m["evidence"]
        e["class"] = verb_class(name, e, manual)
        for alias in (m or {}).get("also_italian", "").split(";") if m else []:
            if alias.strip() and alias.strip() not in e["aliases"]:
                e["aliases"].append(alias.strip())      # töö is also 'prendere', which names ciapà's page
    extra = defaultdict(list)
    for r in read(ETC / "verb_forms_from_texts.csv"):
        extra[key(r["italian"])].append(dict(r, form=shown_form(r["italian"], r["tense"], r["form"], manual)))
    done = {}
    for name in sorted(out, key=lambda n: n not in ("andare", "fare")):     # bases before na föra, fa sù
        out[name]["grid"] = done[name] = full_grid(name, out[name], manual, extra, done)
    return out


