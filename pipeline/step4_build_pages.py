def clitic_order(form):
    """The lessons mostly write 'la/al ciapa' (feminine first) but sometimes 'al/la' or 'la /al': write
    them all 'la/al', to match the label 'le / lü'."""
    form = re.sub(r"\b(?:al\s*/\s*la|la\s*/\s*al)\b", "la/al", form)
    # before a vowel la/al is l' (l'eva fai, l'avrà fai, as in l'è, l'a); ta does not elide (ta evat)
    return re.sub(r"\bla/al\s+(?=[aeiouàèéìòóùöü])", "l’", form)
