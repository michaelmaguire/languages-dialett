def read(path):
    return list(csv.DictReader(path.open())) if path.exists() else []


def key(s):
    return re.sub(r"\s+", " ", s.strip().lower().replace("’", "'"))


def plain(s):
    s = unicodedata.normalize("NFD", s.lower())
    return "".join(c for c in s if c.isalnum() or c == " ").strip()


def bare(italian):
    """'Il mattino' -> 'mattino', for sorting and for matching against word lists."""
    k = key(italian)
    rest = IT_ARTICLE.sub("", k).strip(" .!?\"“”«»")
    return rest if plain(rest) else k.strip(" .!?\"“”«»")      # "uno" alone is the number, not an article


def slug(s):
    s = unicodedata.normalize("NFD", re.sub(r"\.(docx|pdf|txt)$", "", s).lower())
    s = "".join(c for c in s if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-") or "x"


def cell(s):
    return re.sub(r"\s+", " ", str(s)).replace("|", "\\|").strip()


def src_link(source, depth=1, text=None):
    label = text or re.sub(r"\.(docx|pdf|txt)$", "", source)
    return f"[{cell(label)}]({RAW_URL}/blob/main/{quote(source)})"     # depth: kept for callers, unused


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(BANNER + text)


